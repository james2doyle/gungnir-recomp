#!/usr/bin/env python3
"""License machine — T2 (plan TC-2.2, TC-2.3).

Three subcommands over dependencies.json:

  generate              write THIRD_PARTY_NOTICES.txt (per-dependency header
                        block + license text verbatim, from license_file)
  check-coverage        TC-2.2 — every file under third_party/ must live
                        inside a declared dependency path zone; anything
                        unlisted is an unattributed blob and fails by name
  check-licenses        TC-2.3 — every entry's license must be in the
                        GPL-3.0-or-later-compatible approved set
                        (AGENTS.md: CC BY-NC-SA and unattributed code are
                        rejected); failures name the component

Failures are named: UNLISTED_THIRD_PARTY_FILE / LICENSE_REJECTED /
LICENSE_FILE_MISSING. Exit 0 only when everything is accounted for.

Run: python3 tools/package_notices.py {generate|check-coverage|check-licenses} [--root REPO]
"""
import argparse
import json
import sys
from pathlib import Path

APPROVED = {
    "MIT", "ISC", "Zlib", "Unlicense", "CC0-1.0",
    "BSD-1-Clause", "BSD-2-Clause", "BSD-3-Clause",
    "Apache-2.0", "Apache-1.1",
    "LGPL-2.0", "LGPL-2.0-or-later", "LGPL-2.1", "LGPL-2.1-or-later",
    "LGPL-3.0", "LGPL-3.0-or-later",
    "GPL-2.0", "GPL-2.0-or-later", "GPL-3.0", "GPL-3.0-or-later", "GPL-1.0",
}
PROJECT_LICENSE = "GPL-3.0-or-later"


class NoticesError(Exception):
    def __init__(self, name, detail):
        super().__init__(f"{name}: {detail}")
        self.name = name
        self.detail = detail


def die(name, detail):
    raise NoticesError(name, detail)


def load_dependencies(root: Path):
    path = root / "dependencies.json"
    if not path.is_file():
        die("DEPS_MANIFEST_MISSING", str(path))
    data = json.loads(path.read_text())
    deps = data.get("dependencies", [])
    if not deps:
        die("DEPS_MANIFEST_EMPTY", str(path))
    return deps


def third_party_files(root: Path):
    tp = root / "third_party"
    if not tp.is_dir():
        return []
    return sorted(p for p in tp.rglob("*") if p.is_file())


def covered_paths(root: Path, deps):
    """Every third_party file must fall inside a declared path zone."""
    zones = [(root / d["path"]).resolve() for d in deps
             if str(d.get("path", "")).startswith("third_party/")]
    for p in third_party_files(root):
        resolved = p.resolve()
        if not any(resolved.is_relative_to(z) for z in zones):
            die("UNLISTED_THIRD_PARTY_FILE",
                f"{p.relative_to(root).as_posix()} — add a dependencies.json "
                "entry with path/provenance/license or delete the blob")


def license_text(root: Path, entry):
    lf = entry.get("license_file")
    if not lf:
        die("LICENSE_FILE_MISSING",
            f"{entry['name']!r} has no license_file in dependencies.json")
    path = root / lf
    if not path.is_file():
        die("LICENSE_FILE_MISSING",
            f"{entry['name']!r}: license file absent at {lf}")
    return path.read_text()


def licenses(root: Path, deps):
    # Exact-match set only: GPL/LGPL "-or-later" aliases are explicitly named
    # so no fuzzy prefix logic can ever let an incompatible tag slip through.
    or_later = {f"{a}-or-later" for a in APPROVED if a.startswith(("GPL-", "LGPL-"))}
    match = APPROVED | or_later
    for entry in deps:
        name = entry["name"]
        lic = entry.get("license", "")
        if lic not in match:
            die("LICENSE_REJECTED",
                f"{name!r} declares license {lic!r} which is incompatible with "
                f"this project's {PROJECT_LICENSE} (CC BY-NC-SA and unattributed "
                "code are banned by AGENTS.md #2/#3)")
        license_text(root, entry)
        print(f"OK {name} ({lic})")


def generate(root: Path, deps):
    out = root / "THIRD_PARTY_NOTICES.txt"
    blocks = [
        "THIRD_PARTY_NOTICES.txt — generated by tools/package_notices.py.",
        "Do not edit by hand; update dependencies.json / vendored license",
        "files and regenerate. Project license: " + PROJECT_LICENSE + ".",
        "",
    ]
    for entry in deps:
        blocks += [
            "=" * 72,
            f"Component: {entry['name']}",
            f"Upstream: {entry.get('upstream', '?')}",
            f"Commit pinned: {entry.get('commit', '?')}",
            f"License: {entry.get('license', '?')}",
            f"Vendored at: {entry.get('path', '?')}",
            f"Provenance: {entry.get('provenance', 'docs/PROVENANCE.md')}",
            "-" * 72,
        ]
        blocks.append(license_text(root, entry).rstrip() + "\n")
    out.write_text("\n".join(blocks))
    print(f"wrote {out} ({len(deps)} components)")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("cmd", choices=["generate", "check-coverage", "check-licenses"])
    parser.add_argument("--root", default=str(Path(__file__).resolve().parent.parent))
    args = parser.parse_args(argv)
    root = Path(args.root).resolve()
    try:
        if args.cmd == "check-coverage":
            covered_paths(root, load_dependencies(root))
        elif args.cmd == "check-licenses":
            licenses(root, load_dependencies(root))
        elif args.cmd == "generate":
            generate(root, load_dependencies(root))
    except NoticesError as e:
        print(f"NOTICES_ERR {e.name}: {e.detail}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
